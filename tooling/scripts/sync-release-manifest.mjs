#!/usr/bin/env node
/**
 * Snapshot the latest published release into a typed module.
 *
 * Why a file instead of a live call: GitHub's anonymous API allows 60 requests an hour
 * per IP, and Cloudflare Workers share their egress addresses, so the public download
 * endpoint was intermittently answering 403 in production. Deploying from a developer
 * machine hits a different limit, and the snapshot lets a cold Worker answer from real
 * data even when the live call is refused.
 *
 * The snapshot is never invented. If GitHub cannot be read, the previous file stays as it
 * is and the deploy continues: an old real release is better than a fabricated one, and
 * the endpoint marks the answer `x-release-cache: manifest`.
 */
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const target = join(root, "apps/api/src/release-manifest.ts");
const repo = process.env.RELEASES_REPO?.trim() || "laudesmassamba1-ai/PROOFSTACK";

function assetFrom(raw) {
  if (!raw || typeof raw.name !== "string" || typeof raw.browser_download_url !== "string") {
    return null;
  }
  return {
    name: raw.name,
    url: raw.browser_download_url,
    size: typeof raw.size === "number" ? raw.size : 0,
    digest: typeof raw.digest === "string" && raw.digest.length > 0 ? raw.digest : null,
    contentType: typeof raw.content_type === "string" ? raw.content_type : null,
  };
}

const response = await fetch(`https://api.github.com/repos/${repo}/releases/latest`, {
  headers: {
    accept: "application/vnd.github+json",
    "x-github-api-version": "2022-11-28",
    "user-agent": "proofstack-release-manifest",
    ...(process.env.GITHUB_TOKEN ? { authorization: `Bearer ${process.env.GITHUB_TOKEN}` } : {}),
  },
});

if (!response.ok) {
  console.warn(
    `release manifest: GitHub answered HTTP ${response.status}; keeping the existing snapshot.`
  );
  process.exit(0);
}

const raw = await response.json();
if (typeof raw.tag_name !== "string") {
  console.warn("release manifest: GitHub returned no tag; keeping the existing snapshot.");
  process.exit(0);
}

const assets = Array.isArray(raw.assets)
  ? raw.assets.map(assetFrom).filter((item) => item !== null)
  : [];

const body = {
  fetchedAt: new Date().toISOString(),
  release: {
    tag: raw.tag_name,
    name: typeof raw.name === "string" && raw.name.length > 0 ? raw.name : raw.tag_name,
    url:
      typeof raw.html_url === "string"
        ? raw.html_url
        : `https://github.com/${repo}/releases/latest`,
    publishedAt: typeof raw.published_at === "string" ? raw.published_at : "",
    prerelease: raw.prerelease === true,
    assets,
  },
};

const out = `// Generated by tooling/scripts/sync-release-manifest.mjs.
// Do not edit by hand: this is the last release verified from the public source, used
// only when the live GitHub call is rate-limited. Regenerate with \`pnpm releases:sync\`.
export const RELEASE_MANIFEST = ${JSON.stringify(body, null, 2)};
`;

writeFileSync(target, out);
// The file is generated, but it is committed and linted like any other source file.
try {
  execFileSync("npx", ["biome", "format", "--write", target], { cwd: root, stdio: "ignore" });
} catch {
  // Formatting is cosmetic: the generated module is valid TypeScript either way.
}
console.log(
  `release manifest: ${body.release.tag} (${assets.length} assets) written to apps/api/src/release-manifest.ts`
);
