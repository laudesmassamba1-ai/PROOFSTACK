#!/usr/bin/env node

/**
 * Vendor the brand typefaces into `apps/web/public/fonts`.
 *
 * The site loads Archivo, Instrument Sans, Instrument Serif and JetBrains Mono from Google
 * Fonts. The Content-Security-Policy is strict — `font-src 'self' data:` — so every one of
 * those requests was refused and the whole product rendered in fallback system fonts. The
 * page also contacted Google on every visit, which the privacy text does not promise.
 *
 * This downloads the exact files Google's stylesheet points at, keeps the Latin subsets,
 * and writes `apps/web/public/fonts.css` with the same `@font-face` rules rewritten to
 * local paths and the same `unicode-range` values, so a page never silently swaps glyphs.
 *
 * Run again when a family changes:
 *   node tooling/scripts/fetch-fonts.mjs
 */

import { createHash } from "node:crypto";
import { mkdir, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";

const OUT_DIR = "apps/web/public/fonts";
const CSS_FILE = "apps/web/public/fonts.css";

// Google serves woff2 only to a browser-shaped request.
const UA =
  "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36";

/** The four families the design tokens actually name, with the axes the CSS uses. */
const FAMILIES = [
  "Archivo:ital,wdth,wght@0,62..125,100..900;1,62..125,100..900",
  "Instrument+Sans:ital,wght@0,400..700;1,400..700",
  "Instrument+Serif:ital@0;1",
  "JetBrains+Mono:ital,wght@0,100..800;1,100..800",
];

/** Latin only: the interface speaks French and English, and a Cyrillic subset is 60 kB. */
const WANTED_SUBSETS = new Set(["latin", "latin-ext"]);

async function get(url, as = "text") {
  const response = await fetch(url, { headers: { "user-agent": UA } });
  if (!response.ok) throw new Error(`${url} answered HTTP ${response.status}`);
  return as === "text" ? await response.text() : new Uint8Array(await response.arrayBuffer());
}

/** Split Google's stylesheet into `/* subset *\/` + rule blocks. */
function blocks(css) {
  return css
    .split(/\/\*\s*([a-z-]+)\s*\*\//i)
    .slice(1)
    .reduce((acc, part, index, all) => {
      if (index % 2 === 0) acc.push({ subset: part.trim(), rule: all[index + 1] ?? "" });
      return acc;
    }, []);
}

await rm(OUT_DIR, { recursive: true, force: true });
await mkdir(OUT_DIR, { recursive: true });

const sheets = [];
let files = 0;
let bytes = 0;
for (const family of FAMILIES) {
  const css = await get(`https://fonts.googleapis.com/css2?family=${family}&display=swap`);
  for (const { subset, rule } of blocks(css)) {
    if (!WANTED_SUBSETS.has(subset)) continue;
    const url = rule.match(/url\((https:\/\/[^)]+\.woff2)\)/)?.[1];
    if (!url) continue;
    const data = await get(url, "binary");
    // The name comes from the content, so a re-run over the same font keeps the same file
    // and browsers keep their cached copy.
    const hash = createHash("sha256").update(data).digest("hex").slice(0, 12);
    const name = `${(rule.match(/font-family:\s*'([^']+)'/) ?? [undefined, "font"])[1]
      .toLowerCase()
      .replace(/\s+/g, "-")}-${subset}-${hash}.woff2`;
    await writeFile(path.join(OUT_DIR, name), data);
    files += 1;
    bytes += data.length;
    sheets.push(
      `/* ${subset} */\n${rule
        .replace(/\/\*\s*[a-z-]+\s*\*\/\s*/i, "")
        .replace(url, `/fonts/${name}`)
        .trim()}`
    );
  }
}

const header = `/*
 * Brand typefaces, served from this origin.
 *
 * Generated by tooling/scripts/fetch-fonts.mjs from the stylesheet Google Fonts returns to a
 * browser: same families, same axes, same unicode-range values, local files. The
 * Content-Security-Policy allows fonts from 'self' only, so nothing here can be fetched from
 * a third party — and no visitor's address reaches one.
 *
 * ${files} files, ${(bytes / 1024).toFixed(0)} kB total.
 */

`;
await writeFile(CSS_FILE, header + sheets.join("\n\n") + "\n");

const written = await readdir(OUT_DIR);
console.log(`fonts: ${files} files, ${(bytes / 1024).toFixed(0)} kB`);
console.log(`stylesheet: ${CSS_FILE}`);
console.log(`kept: ${written.length} woff2 in ${OUT_DIR}`);
